#!/usr/bin/env node
/**
 * Reproduce the exact 224-seed-term subset without keeping the full dictionary.
 * Offline (default): node src/data/generate-pronunciations.mjs
 * Explicit source refresh: node src/data/generate-pronunciations.mjs --refresh
 * --refresh reads a pinned, public source as a stream, retains only matching
 * seed terms, verifies SHA-256, and never writes the complete dictionary.
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { seedWords } from './seed.ts';

const REVISION = '43c3570eb3553bdd19fccd2bd0091534889af023';
const SOURCE_SHA256 = '2af6f154a5c363275f052d1f85acedef38ed185ca9745aa4314be77f6b70de67';
const SOURCE_URL = `https://raw.githubusercontent.com/open-dict-data/ipa-dict/${REVISION}/data/en_US.txt`;
const SEED_SHA256 = 'bd5263b6c2b058d03bbeb7862df51f70694f0b8a98bf2b2bdb24be004e4f86d9';
const subsetPath = fileURLToPath(new URL('./pronunciations-subset.json', import.meta.url));
const outputPath = fileURLToPath(new URL('./pronunciations.ts', import.meta.url));
const seedBytes = await readFile(new URL('./seed.ts', import.meta.url));
assert.equal(createHash('sha256').update(seedBytes).digest('hex'), SEED_SHA256,
  'Seed changed: review the target terms and coverage before regenerating.');
const terms = seedWords.map(word => word.term.toLowerCase());
const wanted = new Set(terms);
assert.equal(wanted.size, 224);
if (process.argv.slice(2).some(arg => arg !== '--refresh')) throw new Error('Only --refresh is supported.');

let subset;
if (process.argv.includes('--refresh')) {
  const response = await fetch(SOURCE_URL, { signal: AbortSignal.timeout(45_000), redirect: 'error' });
  if (!response.ok) throw new Error(`Public source returned HTTP ${response.status}; stop and review access, do not work around a denial.`);
  assert.ok(response.body, 'Missing source stream.');
  const hash = createHash('sha256');
  const decoder = new TextDecoder('utf-8', { fatal: true });
  const entries = Object.create(null);
  let tail = '', sourceBytes = 0;
  function consume(line) {
    const tab = line.indexOf('\t');
    if (tab < 0) return;
    const term = line.slice(0, tab).trim().toLowerCase();
    if (!wanted.has(term)) return;
    const ipa = line.slice(tab + 1).trim();
    if (Object.hasOwn(entries, term) && entries[term] !== ipa) throw new Error(`Conflicting source row: ${term}`);
    entries[term] = ipa;
  }
  for await (const bytes of response.body) {
    sourceBytes += bytes.length;
    if (sourceBytes > 4_000_000) throw new Error('Pinned source exceeds the expected bound.');
    hash.update(bytes);
    tail += decoder.decode(bytes, { stream: true });
    const lines = tail.split('\n');
    tail = lines.pop();
    for (const line of lines) consume(line);
  }
  tail += decoder.decode();
  if (tail) consume(tail);
  const sourceSha256 = hash.digest('hex');
  assert.equal(sourceSha256, SOURCE_SHA256, 'Pinned source digest mismatch: no output written.');
  subset = { revision: REVISION, url: SOURCE_URL, sourceSha256, sourceBytes,
    entries: Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b, 'en'))),
    missing: terms.filter(term => !Object.hasOwn(entries, term)) };
} else {
  subset = JSON.parse(await readFile(subsetPath, 'utf8'));
}
assert.equal(subset.revision, REVISION);
assert.equal(subset.url, SOURCE_URL);
assert.equal(subset.sourceSha256, SOURCE_SHA256);
assert.equal(subset.sourceBytes, 3_180_267);
const entries = Object.entries(subset.entries).sort(([a], [b]) => a.localeCompare(b, 'en'));
assert.equal(entries.length, 218);
for (const [term, ipa] of entries) {
  assert.ok(wanted.has(term), `Not a seed term: ${term}`);
  assert.equal(typeof ipa, 'string');
  assert.ok(/^\/[^\n]+\/(?:, \/[^\n]+\/)*$/.test(ipa), `Malformed IPA value: ${term}`);
  assert.ok(!/[<>]/.test(ipa), `Unexpected markup: ${term}`);
}
assert.deepEqual(subset.missing, ['resolver', 'hostname', 'runtime', 'namespace', 'gpu', 'checksum']);
if (process.argv.includes('--refresh')) await writeFile(subsetPath, JSON.stringify(subset, null, 2) + '\n');
const output = `/**
 * Generated by generate-pronunciations.mjs; do not invent missing values.
 * Direct General American IPA from ipa-dict, preserving all source variants.
 * Data licenses: MIT and original CMUdict terms; NOT the seed text's CC0.
 * See PRONUNCIATION_SOURCES.md and /licenses/pronunciation-data.txt.
 */
export interface PronunciationEntry {
  ipa: string;
  dialect: 'en-US' | 'en-GB';
  source: string;
}
const SOURCE = 'ipa-dict en_US · ${REVISION.slice(0, 7)}';
export const pronunciationEntries: Readonly<Record<string, PronunciationEntry>> = Object.freeze({
${entries.map(([term, ipa]) => `  ${JSON.stringify(term)}: { ipa: ${JSON.stringify(ipa)}, dialect: 'en-US', source: SOURCE },`).join('\n')}
});

export const pronunciationInfo = Object.freeze({
  name: 'ipa-dict · 通用美式英语 IPA',
  sourceUrl: 'https://github.com/open-dict-data/ipa-dict/tree/${REVISION}',
  license: 'MIT + LicenseRef-CMUdict',
  licenseUrl: '/licenses/pronunciation-data.txt',
  version: '${REVISION}',
  sourceSha256: '${SOURCE_SHA256}',
  dialect: 'en-US' as const,
  coveredCount: 218,
  seedWordCount: 224,
  missingTerms: Object.freeze(['resolver', 'hostname', 'runtime', 'namespace', 'gpu', 'checksum']),
  note: '保留词典全部发音变体，未按词性筛选；6 个未收录词不猜音标。浏览器合成语音不属于词典录音。',
});
`;
await writeFile(outputPath, output);
console.log(`Generated ${entries.length}/${wanted.size} sourced en-US IPA entries; missing: ${subset.missing.join(', ')}`);
